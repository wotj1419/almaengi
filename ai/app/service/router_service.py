class BGEM3Encoder(DenseEncoder):
    """BGE-m3 기반 인코더. 한국어 임베딩 성능이 우수."""

    name: str = "bge-m3"
    type: str = "huggingface"
    score_threshold: float = 0.5
    _model: Any = None

    def __init__(self, score_threshold: float = 0.5) -> None:
        super().__init__(name="bge-m3", score_threshold=score_threshold)
        self._model = BGEM3FlagModel("BAAI/bge-m3", use_fp16=True)

    def __call__(self, docs: list[str]) -> list[list[float]]:
        result = self._model.encode(docs, max_length=512)
        return result["dense_vecs"].tolist()


